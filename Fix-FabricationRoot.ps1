# Function to write colored output
function Write-Status {
    param(
        [string]$Message,
        [string]$Status = "INFO"
    )

    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $statusMap = @{
        "INFO" = @{ Color = "White"; Prefix = "[INFO] " }
        "SUCCESS" = @{ Color = "Green"; Prefix = "[OK] " }
        "WARNING" = @{ Color = "Yellow"; Prefix = "[WARN] " }
        "ERROR" = @{ Color = "Red"; Prefix = "[ERROR] " }
    }

    $statusInfo = $statusMap[$Status]
    if (-not $statusInfo) { $statusInfo = $statusMap["INFO"] }

    $logMessage = "$timestamp $($statusInfo.Prefix)$Message"
    Write-Host $logMessage -ForegroundColor $statusInfo.Color
    Write-Output $logMessage
}

# Function to fix a single Fabrication System instance
function Repair-FabricationInstance {
    param(
        [string]$InstancePath
    )

    Write-Status "Processing instance: $InstancePath" "INFO"

    # 1. Ensure required directories exist
    $requiredDirs = @("Logs", "Reports", "Issues", "Fixes", "Config")
    foreach ($dir in $requiredDirs) {
        $dirPath = Join-Path -Path $InstancePath -ChildPath $dir
        if (-not (Test-Path -Path $dirPath)) {
            try {
                New-Item -ItemType Directory -Path $dirPath -Force | Out-Null
                Write-Status "Created directory: $dirPath" "SUCCESS"
            } catch {
                Write-Status "Failed to create directory $dirPath : $_" "ERROR"
                return $false
            }
        }
    }

    # 2. Check and fix module file
    $moduleFile = Join-Path -Path $InstancePath -ChildPath "FabricationSystem.psm1"
    if (-not (Test-Path -Path $moduleFile)) {
        try {
            @'
# Fabrication System Module
# Auto-generated by Fabrication Root Fixer

function Start-FabricationSystem {
    [CmdletBinding()]
    param(
        [ValidateSet('Active', 'Ruhestand')]
        [string]$Mode = 'Active'
    )
    Write-Host "Fabrication System started in $Mode mode at $(Get-Date)"
}

function Get-SystemStatus {
    [CmdletBinding()]
    param()
    return @{
        Status = "Operational"
        Timestamp = Get-Date
    }
}

Export-ModuleMember -Function Start-FabricationSystem, Get-SystemStatus
'@ | Out-File -FilePath $moduleFile -Encoding utf8 -Force
