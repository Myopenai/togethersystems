            Write-Status "Created script file: $scriptFile" "SUCCESS"
        } catch {
            Write-Status "Failed to create script file: $_" "ERROR"
            return $false
        }
    }

    # 4. Check and fix module manifest
    $manifestFile = Join-Path -Path $InstancePath -ChildPath "FabricationSystem.psd1"
    if (-not (Test-Path -Path $manifestFile)) {
        try {
