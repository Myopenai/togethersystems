        } catch {
            Write-Status "Failed to create module file: $_" "ERROR"
            return $false
        }
    }

    # 3. Check and fix script file
    $scriptFile = Join-Path -Path $InstancePath -ChildPath "FabricationSystem.ps1"
    if (-not (Test-Path -Path $scriptFile)) {
        try {
            @'
