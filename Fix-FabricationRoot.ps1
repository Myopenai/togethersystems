# Main execution
try {
    Write-Status "Starting Fabrication System Root Fixer" "INFO"
    Write-Status "Scanning directory: $rootPath" "INFO"

    # Find all Fabrication System instances
    $instances = @()
    
    # Look for module files
    $moduleFiles = Get-ChildItem -Path $rootPath -Filter "FabricationSystem.psm1" -Recurse -ErrorAction SilentlyContinue
    
    foreach ($file in $moduleFiles) {
        $instancePath = $file.Directory.FullName
        if ($instances -notcontains $instancePath) {
            $instances += $instancePath
        }
    }

    # If no instances found, create one in the root
    if ($instances.Count -eq 0) {
        Write-Status "No Fabrication System instances found. Creating new instance in root directory." "WARNING"
        $newInstancePath = Join-Path -Path $rootPath -ChildPath "FabricationSystem"
        $instances += $newInstancePath
    }

    # Process each instance
    $successCount = 0
    foreach ($instance in $instances) {
        Write-Status "`n=== Processing instance: $instance ===" "INFO"
        $result = Repair-FabricationInstance -InstancePath $instance
        if ($result) {
            $successCount++
            Write-Status "Successfully processed instance: $instance" "SUCCESS"
        } else {
            Write-Status "Failed to process instance: $instance" "ERROR"
        }
        Write-Status "=" * 80 "INFO"
    }

    # Summary
    Write-Status "`n=== Processing Complete ===" "INFO"
    Write-Status "Total instances processed: $($instances.Count)" "INFO"
    Write-Status "Successfully fixed: $successCount" "SUCCESS"
    Write-Status "Failed: $($instances.Count - $successCount)" -Status $(if (($instances.Count - $successCount) -gt 0) { "ERROR" } else { "SUCCESS" })
    Write-Status "Log file: $logFile" "INFO"

} catch {
    Write-Status "Fatal error: $_" "ERROR"
    Write-Status $_.ScriptStackTrace "ERROR"
} finally {
    Write-Host "`nFabrication Root Fixer completed at $(Get-Date)" -ForegroundColor Cyan
    Stop-Transcript
}