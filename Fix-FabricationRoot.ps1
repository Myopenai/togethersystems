            $manifestContent | Out-File -FilePath $manifestFile -Encoding utf8 -Force
            Write-Status "Created module manifest: $manifestFile" "SUCCESS"
        } catch {
            Write-Status "Failed to create module manifest: $_" "ERROR"
            return $false
        }
    }

    # 5. Test the module
    try {
        $moduleName = (Get-Item $moduleFile).BaseName
        Import-Module $moduleFile -Force -ErrorAction Stop
        Write-Status "Successfully imported module: $moduleName" "SUCCESS"
        
        # Test basic functionality
